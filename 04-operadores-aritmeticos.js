// operadores aritmeticos são utilizados para realizar operaçoes matematicas, como por exemplo, somar, subtrair, multiplicar e dividir

const preco = 50;
const frete = 15;

console.log("--------------")


// 1 - adição (+)
// utilizamos esse operador para a soma de valores


console.log(preco + frete)
const soma = preco + frete

console.log("----------------------")

// 2 - subtração (-)
// utilizamos esse operador para realizar a subtração de valores
const subtração = preco - frete

console.log(subtração)
console.log(15 - 10);
console.log(preco - frete);

console.log("-------------------")

// 3 - multiplicação (*)
// utilizamos esse operador para realizar a multiplicação de valores

const multiplicação = preco * frete

console.log(multiplicação)
console.log(15 * 10);
console.log(preco * frete);

console.log("-----------------------------")

// 4 - divisão ( / )
// utilzamos esse operador para realizar a divisão de valores

const divisao = preco / frete

console.log(divisao);
console.log(10 / 0)
console.log(preco / frete);
console.log(10 / 2);

console.log("--------------");

// 5 - exponenciação (**)
// utilizamos esse operador para realizar a exponeciação de valores, ou seja , elevar um numero a uma potencia

const exponeciação = preco ** frete

console.log(exponeciação);
console.log(2 ** 5);

console.log("---------------------");

// 6 - o resto da divisão ( % )
// o operador % retorna o RESTO DA DIVISÃO, não o resultado em si.
// utilizamos esse operador para verificar se um numero é impar ou par.
console.log(8 % 2); // resto 0
console.log(7 % 2); // resto 1

console.log("---------------------");

